// Bundles src/main.ts into a single Apps-Script-safe dist/Code.js.
//
// esbuild's IIFE output hides every function inside a closure, but Apps Script
// finds functions by top-level name: the editor's Run dropdown only lists
// top-level `function` declarations, and triggers / `clasp run` resolve by global
// name. So after bundling, this evaluates the bundle once (module-level code never
// touches an Apps Script global, see test/scaffold.test.ts), reads the keys of the
// `entryPoints` export, and appends one real top-level stub per key that delegates
// into the bundle. Adding an entry point only ever means adding a key there.
//
// Usage: node scripts/build.mjs [--outfile <path>]   (default: dist/Code.js)
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { parseArgs } from 'node:util';
import vm from 'node:vm';
import { build } from 'esbuild';

const GLOBAL_NAME = '__classroomBot';
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const { values } = parseArgs({ options: { outfile: { type: 'string', default: 'dist/Code.js' } } });
const outfile = values.outfile;

const result = await build({
  entryPoints: ['src/main.ts'],
  bundle: true,
  platform: 'neutral',
  format: 'iife',
  target: 'es2020',
  globalName: GLOBAL_NAME,
  write: false,
  logLevel: 'warning',
});
const bundle = result.outputFiles[0].text;

const sandbox = vm.createContext({});
vm.runInContext(bundle, sandbox, { filename: 'Code.js' });
const entryPoints = vm.runInContext(`${GLOBAL_NAME}.entryPoints`, sandbox);
const names = entryPoints ? Object.keys(entryPoints) : [];

if (names.length === 0) {
  throw new Error(`src/main.ts exports no \`entryPoints\` — Apps Script would see no functions.`);
}
for (const name of names) {
  if (!IDENTIFIER.test(name))
    throw new Error(`entryPoints key "${name}" is not a valid function name.`);
  if (typeof entryPoints[name] !== 'function')
    throw new Error(`entryPoints.${name} is not a function.`);
}

const stubs = names
  .map(
    (name) =>
      `function ${name}() {\n  return ${GLOBAL_NAME}.entryPoints.${name}.apply(this, arguments);\n}`,
  )
  .join('\n');

mkdirSync(dirname(outfile), { recursive: true });
writeFileSync(
  outfile,
  `${bundle}\n// Top-level entry points (generated by scripts/build.mjs) — visible to the\n// Apps Script editor's Run dropdown, triggers and \`clasp run\`.\n${stubs}\n`,
);
console.log(`Built ${outfile} with entry points: ${names.join(', ')}`);
